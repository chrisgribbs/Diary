  /** The week a date falls in, for a season from seasons.js. */
  function weekOf(season) {
    const list = WEEKS[season.id] || [];
    const index = Math.floor(season.dayIndex / 7);
    const weeks = Math.ceil(season.length / 7);
    const week = list.length ? list[index % list.length] : null;
    return week && { ...week, index, number: index + 1, weeks, key: `${season.id}-${index % list.length}`,
      firstDay: index * 7, lastDay: Math.min(season.length, index * 7 + 7) - 1 };
  }

  window.WellWriteWeeks = { WEEKS, weekOf };
